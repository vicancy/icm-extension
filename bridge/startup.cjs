const fs = require('node:fs');
const path = require('node:path');

function installStartup({ platform = process.platform, appData = process.env.APPDATA, node = process.execPath, server = path.join(__dirname, 'server.cjs') } = {}) {
  if (platform !== 'win32') return null;
  if (!appData) throw new Error('APPDATA is required to install the Windows sign-in launcher.');
  const file = path.join(appData, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup', 'ICM On-call Workspace.vbs');
  const marker = "' ICM On-call Workspace - generated local backup launcher";
  if (fs.existsSync(file) && !fs.readFileSync(file, 'utf8').startsWith(marker)) throw new Error('The existing startup launcher was not generated by this installer. It has been left untouched.');
  const command = `"${node}" "${server}"`;
  const script = `${marker}\r\nSet shell = CreateObject("WScript.Shell")\r\nshell.Run "${command.replace(/"/g, '""')}", 0, False\r\n`;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, script, 'utf8');
  return file;
}
module.exports = { installStartup };
